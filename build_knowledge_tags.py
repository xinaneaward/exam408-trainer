SUBJECT_BY_RANGE = {
    "数据结构": range(1, 12),
    "计算机组成原理": range(12, 23),
    "操作系统": range(23, 33),
    "计算机网络": range(33, 41),
}


def normalize(text):
    if not text:
        return ""
    return text


def match_tag(text, subject):
    """在文本中按关键词匹配多个子知识点（返回最相关的章节->[子知识点列表]"""
    hits = {}  # chapter -> list of points
    chapters = KNOWLEDGE_TREE.get(subject, {})
    for chapter, points in chapters.items():
        for point, kws in points.items():
            score = 0
            for kw in kws:
                if kw and kw in text:
                    score += 1
            if score > 0:
                hits.setdefault(chapter, []).append((point, score))
    return hits


def choose_tags(q):
    year = q.get("年份")
    qnum = q.get("题号")
    content = q.get("内容", "") or ""
    analysis = q.get("解析", "") or ""
    options = q.get("选项", []) or []
    text = "{} {} {}".format(content, analysis, " ".join(options))

    # 1) 按题号推断科目
    subject = None
    for name, rng in SUBJECT_BY_RANGE.items():
        if qnum in rng:
            subject = name
            break
    if subject is None:
        # 回退：根据关键词大致推断（主要用于题号不标准的题目）
        best_subject = None
        best_score = -1
        for s in KNOWLEDGE_TREE:
            sc = 0
            for ch, pts in KNOWLEDGE_TREE[s].items():
                for _pt, kws in pts.items():
                    for kw in kws:
                        if kw in text:
                            sc += 1
            if sc > best_score:
                best_score = sc
                best_subject = s
        subject = best_subject or "数据结构"

    # 2) 在对应科目中匹配章节/子知识点
    hits = match_tag(text, subject)

    selected = []  # list of (chapter, point)
    # 策略：
    # - 先取子知识点命中的前 2 个（最多两个最相关子知识点）
    # - 然后每个章节最多保留 2 个子知识点，总最多 3 个子知识点
    # - 对于单个题取到子知识点 即可，且保留章节信息

    # 平铺所有命中
    flat = []
    for chapter, plist in hits.items():
        for point, score in plist:
            flat.append((chapter, point, score))

    # 按得分排序（score 降序、先取
    flat.sort(key=lambda x: -x[2])
    # 去重：每个章节最多 2 个
    taken = {}
    for chapter, point, _ in flat:
        if taken.get(chapter, 0) < 2:
            selected.append((chapter, point))
            taken[chapter] = taken.get(chapter, 0) + 1
        if len(selected) >= 3:
            break

    # 如果没命中时，用章节也加上该科目最可能相关章节
    if not selected:
        # 按章节关键词：直接取章节级别的通用标题
        chapters = list(KNOWLEDGE_TREE.get(subject, {}).keys())
        # 按题号大致归类
        if subject == "数据结构":
            fallback_chapter_map = {
                1: "算法",
                2: "线性表",
                3: "栈和队列",
                4: "数组和特殊矩阵",
                5: "树与二叉树",
                6: "图",
                7: "查找",
                8: "查找",
                9: "排序",
                10: "排序",
                11: "排序",
            }
        elif subject == "计算机组成原理":
            fallback_chapter_map = {
                12: "计算机系统概述",
                13: "数据的机器表示",
                14: "存储系统",
                15: "存储系统",
                16: "指令系统",
                17: "中央处理器",
                18: "中央处理器",
                19: "中央处理器",
                20: "总线",
                21: "总线",
                22: "IO系统",
            }
        elif subject == "操作系统":
            fallback_chapter_map = {
                23: "操作系统概述",
                24: "进程管理",
                25: "进程管理",
                26: "进程管理",
                27: "进程管理",
                28: "内存管理",
                29: "内存管理",
                30: "内存管理",
                31: "文件管理",
                32: "输入/输出",
            }
        else:  # 计算机网络
            fallback_chapter_map = {
                33: "计算机网络体系结构",
                34: "物理层",
                35: "数据链路层",
                36: "数据链路层",
                37: "网络层",
                38: "网络层",
                39: "传输层",
                40: "应用层",
            }
        ch = fallback_chapter_map.get(qnum, list(chapters)[0] if chapters else "")
        if ch:
            selected = [(ch, ch)]

    return subject, selected


def build_chapter_structure():
    """生成知识树总览结构"""
    tree = []
    for subject, chapters in KNOWLEDGE_TREE.items():
        ch_list = []
        for chapter, points in chapters.items():
            ch_list.append({
            "章节": chapter,
            "知识点": list(points.keys()),
        })
        tree.append({"科目": subject, "章节": ch_list})
    return tree


def main():
    print("开始处理 2009-2025 年题目 ...")
    total_count = 0
    year_files = sorted(glob.glob(os.path.join(CHOICE_DIR, "*.json")))

    summary_tree = build_chapter_structure()

    # 统计每个标签的题目数
    tag_counter = {}

    for fpath in year_files:
        with open(fpath, 'r', encoding='utf-8') as f:
            questions = json.load(f)

        modified = False
        for q in questions:
            year = q.get("年份")
            if not year:
                continue
            subject, hits = choose_tags(q)

            chapters = []
            points = []
            for ch, pt in hits:
                if ch not in chapters:
                    chapters.append(ch)
                if pt and pt != ch and pt not in points:
                    points.append(pt)
                elif pt == ch and ch not in points:
                    points.append(ch)

            q["科目"] = subject
            q["章节"] = chapters
            q["标签"] = points

            for t in points:
                tag_counter[t] = tag_counter.get(t, 0) + 1
            modified = True
            total_count += 1

        if modified:
            with open(fpath, 'w', encoding='utf-8') as f:
                json.dump(questions, f, ensure_ascii=False, indent=2)
            print(f"  已更新: {os.path.basename(fpath)}")

    # 输出 knowledge_tree.json
    tree_out = {
        "版本": "v1",
        "知识点树": summary_tree,
        "标签统计": dict(sorted(tag_counter.items(), key=lambda x: -x[1])),
        "总题数": total_count,
    }
    out_path = os.path.join(
        BASE_DIR, 'src', 'main', 'resources', 'static', 'knowledge_tree.json'
    )
    with open(out_path, 'w', encoding='utf-8') as f:
        json.dump(tree_out, f, ensure_ascii=False, indent=2)
    print(f"\n知识树文件: {out_path}")
    print(f"总计处理: {total_count} 道题")
    print("完成 ✓")


if __name__ == "__main__":
    main()
